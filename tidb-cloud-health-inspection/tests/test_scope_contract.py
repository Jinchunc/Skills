import json
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]


class ScopeContractTests(unittest.TestCase):
    def read(self, relative: str) -> str:
        return (ROOT / relative).read_text(encoding="utf-8")

    def test_one_public_runner_is_documented(self):
        readme = self.read("README.md")
        self.assertIn("python3 scripts/health_inspection.py inspect", readme)
        self.assertIn("Other Python files are implementation modules, not alternate workflows", readme)
        self.assertNotIn("python3 scripts/dedicated_health_inspection.py", readme)
        self.assertNotIn("scripts/checklist-collect.sh", readme)

    def test_shared_health_includes_owner_sql_topn_by_digest(self):
        readme = self.read("README.md")
        # Shared-plan Health now includes the customer's OWN SQL Top-N by digest,
        # while raw SQL text / execution users stay deep-dive only.
        self.assertIn("never raw SQL text", readme)
        self.assertIn("deep-dive only", readme)
        # The old blanket "default Health excludes Top-N" wording must be gone.
        self.assertNotIn("SQL text, digest lists, Top-N SQL, or execution users", readme)

    def test_logical_collection_layer_keeps_scope_guard(self):
        adapters = self.read("scripts/collection_adapters.py")
        self.assertIn("physical_infrastructure_queried", adapters)
        self.assertIn("logical_cluster_only", adapters)
        # The recipes a SHARED plan can select must not reference physical-
        # infrastructure metric families. Dedicated-only recipes (TIKV/PD/INF…)
        # legitimately use physical metrics and share the same file; they are never
        # selectable by a shared plan (selection-time scope guard), so they are
        # exempt. We therefore scope this check to the shared-selectable recipes.
        import sys
        sys.path.insert(0, str(ROOT / "scripts"))
        from checklist_registry import SelectionRequest, load_registry, select_checks
        registry = load_registry(str(ROOT / "config" / "checklist.v1.json"))
        shared_selectable: set[str] = set()
        for plan in ("Starter", "Essential", "Premium"):
            sel = select_checks(registry, SelectionRequest(plan, "health", "individual_cluster"))
            shared_selectable.update(sel["runnable_check_ids"])
        all_recipes = json.loads(self.read("config/collection.v1.json"))["recipes"]
        logical_recipes = json.dumps(
            {cid: r for cid, r in all_recipes.items() if cid in shared_selectable})
        for prohibited in (
            "tikv_engine_size_bytes",
            "pd_scheduler_store_status",
            "node_disk_",
            "tikv_raftstore_",
            "tikv_storage_",
            "tikv_engine_compaction",
        ):
            self.assertNotIn(prohibited, logical_recipes)

    def test_unified_runner_default_denies_unknown_plan(self):
        script = self.read("scripts/health_inspection.py")
        self.assertIn('if plan == "Unknown"', script)
        self.assertIn("cluster Plan could not be determined safely", script)

    def test_registry_uses_python_logical_adapter(self):
        registry = json.loads(self.read("config/checklist.v1.json"))
        self.assertIn("collection_layer", registry["adapters"])
        self.assertEqual(registry["adapters"]["collection_layer"]["kind"], "python")
        self.assertNotIn("logical_health", registry["adapters"])
        self.assertNotIn("shared_health", registry["adapters"])
        serialized = json.dumps(registry["checks"])
        self.assertNotIn('"logical_health"', serialized)
        self.assertNotIn('"shared_health"', serialized)

    def test_plan_checklist_matrix_is_generated_from_registry(self):
        registry = self.read("config/checklist.v1.json")
        matrix = self.read("references/plan-checklist-matrix.md")
        self.assertIn('"source_of_truth": true', registry)
        self.assertIn("Do not edit this file directly", matrix)
        for category in range(14):
            self.assertIn(f"CAT-{category:02d}", registry)
            self.assertIn(f"CAT-{category:02d}", matrix)
        for plan in ("Starter", "Essential", "Premium", "Dedicated", "BYOC"):
            self.assertIn(plan, registry)
            self.assertIn(plan, matrix)


if __name__ == "__main__":
    unittest.main()
