from __future__ import annotations

import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
sys.path.insert(0, str(SCRIPTS))

from checklist_registry import (  # noqa: E402
    RegistryError,
    SelectionRequest,
    load_registry,
    render_markdown,
    select_checks,
    validate_registry,
)
from inspection_gate import validate_check_coverage  # noqa: E402


class ChecklistRegistryTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.registry = load_registry()

    def test_registry_is_complete_and_unique(self) -> None:
        self.assertEqual(14, len(self.registry["categories"]))
        self.assertEqual(109, len(self.registry["checks"]))
        self.assertEqual(109, len({item["id"] for item in self.registry["checks"]}))
        validate_registry(self.registry)

    def test_generated_markdown_is_current(self) -> None:
        actual = (ROOT / "references" / "plan-checklist-matrix.md").read_text(encoding="utf-8")
        self.assertEqual(render_markdown(self.registry), actual)
        self.assertIn("Do not edit this file directly", actual)

    def test_shared_plans_never_select_physical_categories(self) -> None:
        physical = {"CAT-05", "CAT-06", "CAT-07", "CAT-08"}
        for plan in ("Starter", "Essential", "Premium"):
            selected = select_checks(
                self.registry,
                SelectionRequest(plan, "health", "individual_cluster", capabilities=frozenset({"all"})),
            )
            physical_rows = [row for row in selected["checks"] if row["category"] in physical]
            self.assertTrue(physical_rows)
            self.assertTrue(all(row["disposition"] == "prohibited" for row in physical_rows))
            self.assertFalse(set(selected["runnable_check_ids"]) & {row["check_id"] for row in physical_rows})

    def test_capability_without_runtime_adapter_remains_na(self) -> None:
        without = select_checks(
            self.registry,
            SelectionRequest("Premium", "health", "individual_cluster"),
        )
        with_cap = select_checks(
            self.registry,
            SelectionRequest("Premium", "health", "individual_cluster", capabilities=frozenset({"component.resource_control"})),
        )
        self.assertIn("RCU-02", without["na_check_ids"])
        self.assertNotIn("RCU-02", without["runnable_check_ids"])
        self.assertIn("RCU-02", with_cap["na_check_ids"])
        self.assertNotIn("RCU-02", with_cap["runnable_check_ids"])
        row = next(item for item in with_cap["checks"] if item["check_id"] == "RCU-02")
        self.assertEqual(row["reason"], "no_runtime_adapter")

    def test_unknown_is_default_deny(self) -> None:
        result = select_checks(
            self.registry,
            SelectionRequest("Unknown", "health", "individual_cluster", capabilities=frozenset({"all"})),
        )
        self.assertTrue(result["default_denied"])
        self.assertEqual([], result["runnable_check_ids"])
        self.assertEqual([], result["selected_check_ids"])
        self.assertTrue(result["prohibited_check_ids"])

    def test_sql_deep_dive_selects_only_sql_deep_dive_category(self) -> None:
        result = select_checks(
            self.registry,
            SelectionRequest("Premium", "component_deep_dive", "individual_cluster", component="sql"),
        )
        # SQLD-01/02/03 (RU / slow-count / slow-duration Top-N) are now part of the
        # shared-plan Health report (profile=health), so the SQL deep-dive set is 04..09.
        self.assertEqual({f"SQLD-{i:02d}" for i in range(4, 10)}, set(result["selected_check_ids"]))
        self.assertEqual(set(), set(result["runnable_check_ids"]))
        self.assertEqual(set(result["selected_check_ids"]), set(result["na_check_ids"]))

    def test_organization_scope_does_not_expand_to_cluster_checks(self) -> None:
        result = select_checks(
            self.registry,
            SelectionRequest("Dedicated", "health", "organization", capabilities=frozenset({"component.organization"})),
        )
        self.assertTrue(result["checks"])
        self.assertTrue(all(row["category"] == "CAT-13" for row in result["checks"]))

    def test_component_deep_dive_requires_component(self) -> None:
        with self.assertRaises(RegistryError):
            select_checks(self.registry, SelectionRequest("Dedicated", "component_deep_dive", "individual_cluster"))

    def test_gate_rejects_prohibited_or_out_of_selection_check(self) -> None:
        selection = select_checks(
            self.registry,
            SelectionRequest("Premium", "health", "individual_cluster"),
        )
        with self.assertRaises(ValueError):
            validate_check_coverage({"executed_check_ids": ["TIKV-01"]}, selection)

    def test_gate_marks_legacy_unbound_coverage(self) -> None:
        selection = select_checks(
            self.registry,
            SelectionRequest("Dedicated", "health", "individual_cluster"),
        )
        coverage = validate_check_coverage({}, selection)
        self.assertEqual("unbound", coverage["binding"])
        self.assertFalse(coverage["complete"])

    def test_malformed_registry_fails_closed(self) -> None:
        mutated = json.loads(json.dumps(self.registry))
        check = next(item for item in mutated["checks"] if item["id"] == "TIKV-01")
        check["applicability"]["Premium"] = "C"
        with self.assertRaises(RegistryError):
            validate_registry(mutated)


if __name__ == "__main__":
    unittest.main()
